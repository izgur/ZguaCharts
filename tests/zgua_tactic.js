const assert = require('node:assert/strict');
const backtest = require('../core/backtest');
const candles = Array.from({length:8},(_,i)=>({time:100+i*60,open:100+i,close:101+i,high:102+i,low:99+i,volume:100}));
const event=(i,bullish,kind='regular')=>({kind,bullish,firstTime:100,pivotTime:160,confirmedAt:candles[i].time,studies:['RSI']});
const run=events=>backtest.runBacktestOnCandles({strategy:'ZGUA',candles,interval:'1m',params:{feePct:.055,slippagePct:.02},divergenceEvents:events});
const result=run([event(2,true),event(3,true),event(5,false)]);
assert.equal(result.trades,1);assert.equal(result.tradeList[0].entryTime,candles[2].time);assert.equal(result.tradeList[0].exitTime,candles[5].time);
assert.equal(result.tradeList[0].entryPrice,candles[2].open*1.0002);assert.ok(result.totalFees>0);assert.ok(result.totalSlippageCost>0);
assert.equal(result.trade_list[0].entry_reason,'regular bullish divergence (RSI)');
assert.equal(result.trade_list[0].exit_reason,'regular bearish divergence (RSI)');
const multi=run([event(2,true),{...event(2,true,'hidden'),studies:['MACD','CMF']},event(5,false,'weak')]);
assert.match(multi.trade_list[0].entry_reason,/regular bullish.*hidden bullish.*MACD, CMF/);
assert.equal(multi.trade_list[0].exit_reason,'weak bearish divergence (RSI)');
assert.equal(run([event(2,true),event(2,false)]).trades,0);
assert.equal(run([event(2,true),event(5,true),event(5,false)]).trades,1);
const open=run([event(2,true)]);assert.equal(open.trades,0);assert.ok(open.openTrade);
assert.equal(run([event(2,true,'engulfing'),event(5,false)]).trades,0);
assert.throws(()=>backtest.runBacktestOnCandles({strategy:'ZGUA',candles}),/requires/);
console.log('ZGUA next-open fills, costs, conflicts, divergence-only rules and unforced final position passed');
