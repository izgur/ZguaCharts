const assert = require("node:assert/strict");
const { chromium } = require("playwright");

(async () => {
  const browser = await chromium.launch({ headless: true, channel: "msedge" });
  try {
    const context = await browser.newContext({ viewport: { width: 1400, height: 900 }, permissions: ["clipboard-read", "clipboard-write"] });
    const page = await context.newPage(), errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto("http://127.0.0.1:5000/charts");
    const picker = page.locator(".indicator-menu:visible").first();
    await page.locator(".indicator-button:visible").first().click();
    assert.equal(await picker.locator(".indicator-source-button").count(), await page.evaluate(() => config.indicators.length));
    await picker.locator(".indicator-search").fill("utbot");
    const row = picker.locator(".indicator-picker-row:visible");
    const checked = await row.locator("input").isChecked();
    await row.locator(".indicator-source-button").click();
    const dialog = page.locator(".indicator-source-dialog");
    await dialog.locator(".source-copy:not([disabled])").waitFor();
    assert.equal(await row.locator("input").isChecked(), checked);
    assert.match(await dialog.locator("h2").innerText(), /UT Bot/);
    assert.match(await dialog.locator("textarea").inputValue(), /utbot/);
    assert.equal(await dialog.locator(".source-files button").count(), 0);
    await dialog.locator(".source-copy").click();
    assert.match(await page.evaluate(() => navigator.clipboard.readText()), /def calculate\(/);
    const downloadPromise = page.waitForEvent("download");
    await dialog.locator(".source-download").click();
    const download = await downloadPromise;
    assert.equal(download.suggestedFilename(), "utbot.py");
    await page.screenshot({ path: "reports/indicator-source-viewer-20261006.png" });
    await page.keyboard.press("Escape");
    await dialog.waitFor({ state: "detached" });
    assert.equal(await dialog.count(), 0);
    await page.locator(".indicator-button:visible").first().click();
    await picker.locator(".indicator-search").fill("vixfix");
    await picker.locator(".indicator-picker-row:visible input").check();
    await page.locator(".indicator-button:visible").first().click();
    await page.mouse.click(700, 600);
    await page.locator(".chart-indicator-label").first().hover();
    const legendButton = page.locator('.chart-indicator-labels button[title="View Python source"]').first();
    await legendButton.click();
    await dialog.locator(".source-copy:not([disabled])").waitFor();
    assert.match(await dialog.locator("textarea").inputValue(), /vixfix/);
    await dialog.locator(".source-close").click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator(".indicator-button:visible").first().click();
    const box = await picker.boundingBox();
    assert.ok(box.x >= 0 && box.x + box.width <= 390);
    await picker.locator(".indicator-search").fill("rsi");
    await picker.locator(".indicator-picker-row:visible .indicator-source-button").first().click();
    await dialog.locator(".source-copy:not([disabled])").waitFor();
    const sourceBox = await dialog.boundingBox();
    assert.ok(sourceBox.x >= 0 && sourceBox.x + sourceBox.width <= 390);
    assert.ok(sourceBox.y >= 0 && sourceBox.y + sourceBox.height <= 844);
    await page.screenshot({ path: "reports/indicator-source-mobile-20261006.png" });
    assert.deepEqual(errors, []);
    console.log("Browser source checks passed: all catalogue actions, formula focus, copy, ZIP download, legend access and mobile layout.");
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
